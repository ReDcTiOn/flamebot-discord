import {
  Activity,
  Clock,
  Coins,
  Gift,
  Hash,
  House,
  Image as ImageIcon,
  KeyRound,
  Layers,
  LayoutDashboard,
  Link2,
  List,
  Map as MapIcon,
  Megaphone,
  MessageSquare,
  Mic,
  Package,
  Palette,
  Plus,
  Plug,
  Repeat,
  Ruler,
  Search,
  Server,
  Shield,
  Store,
  Ticket,
  ThumbsUp,
  TrendingUp,
  Users,
  type LucideIcon,
} from "lucide-react";
import type { IconName } from "@/modules";
import { ScrapIcon } from "./ScrapIcon";

const ICONS: Record<Exclude<IconName, "scrap">, LucideIcon> = {
  dashboard: LayoutDashboard,
  trending: TrendingUp,
  thumb: ThumbsUp,
  store: Store,
  users: Users,
  hash: Hash,
  message: MessageSquare,
  coin: Coins,
  shield: Shield,
  list: List,
  home: House,
  clock: Clock,
  ruler: Ruler,
  repeat: Repeat,
  palette: Palette,
  megaphone: Megaphone,
  mic: Mic,
  layers: Layers,
  package: Package,
  search: Search,
  image: ImageIcon,
  server: Server,
  activity: Activity,
  gift: Gift,
  ticket: Ticket,
  plus: Plus,
  map: MapIcon,
  plug: Plug,
  link: Link2,
  key: KeyRound,
};

export function Icon({ name, size = 16 }: { name: IconName; size?: number }) {
  if (name === "scrap") return <ScrapIcon size={Math.round(size * 1.25)} alt="" />;
  const Component = ICONS[name];
  return <Component size={size} aria-hidden="true" strokeWidth={1.8} />;
}
